create table if not exists public.jokes (
  id bigint generated by default as identity primary key,
  setup text not null,
  punchline text not null,
  category text not null default 'General',
  created_at timestamptz not null default now()
);

alter table public.jokes enable row level security;

drop policy if exists "Anyone can read jokes" on public.jokes;
create policy "Anyone can read jokes"
on public.jokes
for select
to anon
using (true);

insert into public.jokes (setup, punchline, category)
select seed.setup, seed.punchline, seed.category
from (
  values
    ('Why do programmers prefer dark mode?', 'Because light attracts bugs.', 'Programming'),
    ('Why did the database administrator leave the party?', 'There were too many table relationships.', 'Database'),
    ('What did one wall say to the other wall?', 'I will meet you at the corner.', 'Classic'),
    ('Why was the math book sad?', 'It had too many problems.', 'School')
) as seed(setup, punchline, category)
where not exists (select 1 from public.jokes);
